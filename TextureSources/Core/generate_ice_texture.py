"""Generate a translucent ice tile for the reserved atlas slot.

Cool blue body colors and sparse bright cracks distinguish ice from snow while
letting the world show faintly through the face, like the existing glass tile.
"""

from pathlib import Path

from PIL import Image


OUTPUT = Path(__file__).with_name("ice.png")
COLORS = {
    "body": (104, 169, 228, 112),
    "frost": (153, 206, 242, 130),
    "light": (198, 230, 250, 158),
    "shadow": (72, 132, 202, 130),
    "deep": (55, 110, 181, 152),
    "crack": (225, 244, 255, 192),
}


def paint(image, name, points):
    for x, y in points:
        image.putpixel((x, y), COLORS[name])


def main():
    image = Image.new("RGBA", (16, 16), COLORS["body"])

    paint(image, "frost", [
        (1, 0), (2, 0), (6, 0), (7, 0), (12, 0),
        (1, 1), (2, 1), (7, 1), (8, 1), (12, 1), (13, 1),
        (0, 2), (3, 2), (8, 2), (9, 2), (14, 2),
        (3, 3), (4, 3), (9, 3), (10, 3), (14, 3),
        (4, 4), (5, 4), (10, 4), (11, 4), (15, 4),
        (0, 5), (5, 5), (6, 5), (11, 5), (12, 5),
        (1, 6), (6, 6), (7, 6), (12, 6), (13, 6),
        (1, 7), (2, 7), (7, 7), (8, 7), (13, 7),
        (2, 8), (3, 8), (8, 8), (9, 8), (14, 8),
        (3, 9), (4, 9), (9, 9), (10, 9), (15, 9),
        (0, 10), (4, 10), (5, 10), (10, 10), (11, 10),
        (0, 11), (1, 11), (5, 11), (6, 11), (11, 11),
        (1, 12), (2, 12), (6, 12), (7, 12), (12, 12),
        (2, 13), (3, 13), (7, 13), (8, 13), (13, 13),
        (3, 14), (4, 14), (8, 14), (9, 14), (14, 14),
        (4, 15), (5, 15), (9, 15), (10, 15), (15, 15),
    ])
    paint(image, "shadow", [
        (4, 0), (10, 0), (15, 1), (5, 2), (12, 2),
        (1, 3), (6, 3), (13, 3), (2, 4), (7, 4),
        (3, 5), (8, 5), (14, 5), (4, 6), (9, 6),
        (0, 7), (5, 7), (10, 7), (15, 7),
        (1, 8), (6, 8), (11, 8), (2, 9), (7, 9),
        (12, 9), (3, 10), (8, 10), (13, 10),
        (4, 11), (9, 11), (14, 11), (0, 12),
        (5, 12), (10, 12), (15, 12), (1, 13),
        (6, 13), (11, 13), (2, 14), (7, 14),
        (12, 14), (3, 15), (8, 15), (13, 15),
    ])
    paint(image, "deep", [
        (5, 2), (13, 3), (3, 5), (10, 7),
        (6, 8), (2, 9), (13, 10), (5, 12), (12, 14),
    ])
    paint(image, "light", [
        (0, 0), (8, 0), (15, 2), (2, 3), (10, 3),
        (5, 4), (12, 5), (0, 6), (8, 6), (14, 7),
        (3, 8), (9, 8), (1, 10), (11, 10),
        (6, 11), (15, 11), (2, 12), (8, 13),
        (0, 14), (10, 14), (5, 15),
    ])

    # Short branching fractures read as ice rather than snow at 16x16.
    paint(image, "crack", [
        (3, 1), (4, 2), (5, 3), (6, 4), (7, 5),
        (8, 5), (9, 4), (10, 4), (7, 6), (7, 7),
        (11, 9), (10, 10), (9, 11), (8, 12),
        (7, 12), (6, 11), (5, 11), (8, 13), (8, 14),
    ])
    image.save(OUTPUT)


if __name__ == "__main__":
    main()
